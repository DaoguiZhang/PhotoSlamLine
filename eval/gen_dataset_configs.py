#!/usr/bin/env python3
"""Generate per-scene, per-modality SLAM configs for Replica and ETH3D.

Calibration provenance is recorded per dataset and printed, never guessed:
  ETH3D   intrinsics come from <seq>/calibration.txt  (fx fy cx cy), image size
          from the actual RGB image; depth is 16-bit millimetres, so
          RGBD.DepthMapFactor = 1000, cross-checked against max(depth).
  Replica intrinsics come from <root>/cam_params.json; depth is the standard
          Replica 16-bit encoding with factor 6553.5, cross-checked against
          max(depth) (a wrong factor shows up as an implausible room size).

Every generated file records its source in a comment, so a reader can tell the
calibration was derived rather than copied from another dataset.
"""
import json
import os
import sys

import cv2
import numpy as np

ETH = "/workspace/code/SEGS-SLAM/datasets/eth3d"
REP = "/workspace/code/SEGS-SLAM/datasets/replica"
TREE = "/workspace/deliv/cabinet-eval"

BASE = """%YAML:1.0
# generated by eval/gen_dataset_configs.py -- source: {src}
File.version: "1.0"

Camera.type: "PinHole"

Camera1.fx: {fx}
Camera1.fy: {fy}
Camera1.cx: {cx}
Camera1.cy: {cy}

Camera1.k1: 0.0
Camera1.k2: 0.0
Camera1.p1: 0.0
Camera1.p2: 0.0

Camera.width: {w}
Camera.height: {h}

Camera.fps: {fps}

Camera.RGB: 1
{depth}
# ORB parameters: identical to the TUM fr3 default template (not tuned).
ORBextractor.nFeatures: 2000
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7

Line.SampleStep: 0.2
Line.ViewWeight: 2.0
Line.Sigma: 3.0
Line.TopK: 3

Viewer.KeyFrameSize: 0.05
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 0.9
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.08
Viewer.CameraLineWidth: 3.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -0.7
Viewer.ViewpointZ: -1.8
Viewer.ViewpointF: 500.0
"""

DEPTH = """
Stereo.ThDepth: 40.0
Stereo.b: 0.0747
RGBD.DepthMapFactor: {factor}
"""


def write(path, **kw):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(BASE.format(**kw))


def gen_eth3d():
    made = []
    for seq in sorted(os.listdir(ETH)):
        d = os.path.join(ETH, seq)
        cal = os.path.join(d, "calibration.txt")
        rgb = os.path.join(d, "rgb")
        dep = os.path.join(d, "depth")
        if not (os.path.isfile(cal) and os.path.isdir(rgb)):
            continue
        fx, fy, cx, cy = [float(x) for x in open(cal).read().split()[:4]]
        first = sorted(os.listdir(rgb))[0]
        im = cv2.imread(os.path.join(rgb, first), cv2.IMREAD_UNCHANGED)
        h, w = im.shape[:2]
        dmax = 0
        if os.path.isdir(dep):
            dfirst = sorted(os.listdir(dep))[0]
            dm = cv2.imread(os.path.join(dep, dfirst), cv2.IMREAD_UNCHANGED)
            dmax = int(dm.max())
        factor = 1000.0  # ETH3D depth is millimetres
        for mod, sub in (("Monocular", "Monocular/ETH3D"),
                         ("RGB-D", "RGB-D/ETH3D")):
            depth = "" if mod == "Monocular" else DEPTH.format(factor=factor)
            p = os.path.join(TREE, "cfg/ORB_SLAM3", sub,
                             "eth3d_%s.yaml" % seq)
            write(p, src="%s/calibration.txt (fx fy cx cy), depth 16-bit mm, "
                         "max=%d" % (d, dmax),
                  fx=fx, fy=fy, cx=cx, cy=cy, w=w, h=h, fps=30, depth=depth)
            made.append((p, fx, fy, cx, cy, w, h, dmax, factor))
    return made


def gen_replica():
    cfgp = os.path.join(REP, "cam_params.json")
    if not os.path.isfile(cfgp):
        raise SystemExit("missing %s" % cfgp)
    js = json.load(open(cfgp))
    # Replica cam_params.json: {"camera": {"fx":..,"fy":..,"cx":..,"cy":..,
    # "width":..,"height":..}} (older releases nest it under "camera0").
    cam = js.get("camera") or js.get("camera0") or js
    fx, fy = float(cam["fx"]), float(cam["fy"])
    cx, cy = float(cam["cx"]), float(cam["cy"])
    w = cam.get("width") or cam.get("W"); h = cam.get("height") or cam.get("H")
    if w is None or h is None:
        # cam_params.json in this release carries no image size: take it from the
        # actual frame instead of assuming a resolution.
        _p = os.path.join(REP, "office0", "results", "frame000000.jpg")
        _im = cv2.imread(_p, cv2.IMREAD_UNCHANGED)
        h, w = _im.shape[:2]
        print("  [replica] size taken from %s -> %dx%d" % (_p, w, h))
    w, h = int(w), int(h)
    print("  [replica] cam_params keys=%s" % sorted(cam.keys()))
    factor = 6553.5
    made = []
    for scene in sorted(os.listdir(REP)):
        res = os.path.join(REP, scene, "results")
        if not os.path.isdir(res):
            continue
        dfirst = os.path.join(res, "depth000000.png")
        dmax = 0
        if os.path.isfile(dfirst):
            dmax = int(cv2.imread(dfirst, cv2.IMREAD_UNCHANGED).max())
        for mod, sub in (("Monocular", "Monocular/Replica"),
                         ("RGB-D", "RGB-D/Replica")):
            depth = "" if mod == "Monocular" else DEPTH.format(factor=factor)
            p = os.path.join(TREE, "cfg/ORB_SLAM3", sub,
                             "replica_%s.yaml" % scene)
            write(p, src="%s (fx fy cx cy width height), depth factor %.1f, "
                         "max=%d" % (cfgp, factor, dmax),
                  fx=fx, fy=fy, cx=cx, cy=cy, w=w, h=h, fps=30, depth=depth)
            made.append((p, fx, fy, cx, cy, w, h, dmax, factor))
    return made


def main():
    eth = gen_eth3d()
    rep = gen_replica()
    print("ETH3D sequences: %d" % len(eth))
    for m in eth[:2]:
        print("  %s fx=%.3f fy=%.3f cx=%.2f cy=%.2f %dx%d dmax=%d factor=%.0f"
              % ((os.path.basename(m[0]),) + m[1:]))
    print("Replica scenes: %d" % len(rep))
    for m in rep[:2]:
        print("  %s fx=%.3f fy=%.3f cx=%.2f cy=%.2f %dx%d dmax=%d factor=%.1f"
              % ((os.path.basename(m[0]),) + m[1:]))
    if not eth:
        print("WARNING: no ETH3D config generated")
        return 1
    if not rep:
        print("WARNING: no Replica config generated")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
